#!/usr/bin/env python3
"""Generate font IDs and sentinel guards from font header contents."""
import hashlib
from pathlib import Path


FONT_FILES = {}
for family in ('notoserif', 'notosans'):
    for size in (12, 14, 16, 18):
        FONT_FILES[f'{family.upper()}_{size}_FONT_ID'] = tuple(
            f'{family}_{size}_{style}.h' for style in ('regular', 'bold', 'bolditalic', 'italic'))
FONT_FILES.update({
    'UI_10_FONT_ID': ('ubuntu_10_regular.h', 'ubuntu_10_bold.h'),
    'UI_12_FONT_ID': ('ubuntu_12_regular.h', 'ubuntu_12_bold.h'),
    'SMALL_FONT_ID': ('notosans_8_regular.h',),
    'CHINESE_CHESS_FONT_ID': ('chinese_chess_16.h',),
    'CONTROL_18_FONT_ID': ('notosans_18_regular.h', 'notosans_18_bold.h'),
})


def font_ids(directory):
    return {name: sum(int.from_bytes(hashlib.sha256((directory / filename).read_bytes()).digest(), 'big')
                      for filename in filenames) % (2 ** 32) - (2 ** 31)
            for name, filenames in FONT_FILES.items()}


def render_header(ids):
    lines = ['// The contents of this file are generated by ./lib/EpdFont/scripts/build-font-ids.sh',
             '#pragma once', '']
    lines += [f'#define {name} ({value})' for name, value in ids.items()]
    lines += ['', '// Font ID 0 is reserved as the "not found" sentinel.',
              '// Guard against any hash accidentally producing 0.']
    lines += [f'static_assert({name} != 0, "Font ID collision with sentinel");' for name in ids]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    print(render_header(font_ids(Path(__file__).resolve().parent.parent / 'builtinFonts')), end='')
