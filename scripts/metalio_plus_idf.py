"""Materialize the ignored root CMake file without conflicting with C3 rebuilds."""

from pathlib import Path

MARKER = "# Generated by scripts/metalio_plus_idf.py; do not edit.\n"
READER_WRAPS = "-Wl,--wrap=panic_print_backtrace,--wrap=panic_abort,--wrap=bootloader_common_check_efuse_blk_validity"


def without_reader_wraps(flags):
    # Preserve quoting and every other option; do not shell-tokenize defines.
    if isinstance(flags, str):
        return flags.replace(READER_WRAPS, "")
    return [flag.replace(READER_WRAPS, "") for flag in flags if flag != READER_WRAPS]


def prepare_project(project: Path) -> None:
    target = project / "CMakeLists.txt"
    wanted = MARKER + (project / "config/metalio_plus_project.cmake").read_text()
    if target.exists():
        current = target.read_text()
        if current == wanted:
            return
        generated_default = (
            "cmake_minimum_required(VERSION 3.16.0)\n"
            "include($ENV{IDF_PATH}/tools/cmake/project.cmake)\n"
            f"project({project.name})\n"
        )
        if not current.startswith(MARKER) and current != generated_default:
            raise RuntimeError("Metalio Plus will not overwrite an unrecognized root CMakeLists.txt")
    target.write_text(wanted)


try:
    Import("env")
except NameError:
    env = None

if env is not None:
    prepare_project(Path(env.subst("$PROJECT_DIR")))
    # PlatformIO applies BUILD_UNFLAGS after BuildFrameworks(), too late to
    # protect the bootloader env cloned inside IDF. Remove app hooks before
    # flags are parsed; the post script restores them on the application only.
    env.Replace(BUILD_FLAGS=without_reader_wraps(env.get("BUILD_FLAGS", [])),
                METALIO_PLUS_READER_WRAPS=READER_WRAPS)
